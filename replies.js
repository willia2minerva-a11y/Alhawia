const pickOne = a => a[Math.floor(Math.random() * a.length)];
function countTokens(n) { return n ? n.split(' ').length : 0; }
// يعيد { r, mood } أو null
function localReply(text) {
  const n = clean(String(text || '').slice(0, 300));
  if (!n) return null;
  const nt = countTokens(n);
  for (const p of PH) if (nt <= p.max && p.re.test(n)) return { r: pickOne(p.r), mood: p.m };
  return null;
}

