// توحيد الحروف: حذف التشكيل والتطويل، وتوحيد الألف والياء والتاء المربوطة
const fold = s => String(s || '').toLowerCase()
  .replace(/[\u064B-\u065F\u0670\u0640]/g, '')
  .replace(/[أإآٱ]/g, 'ا').replace(/ى/g, 'ي').replace(/ة/g, 'ه').replace(/ئ/g, 'ي').replace(/ؤ/g, 'و')
  .replace(/ک/g, 'ك').replace(/ی/g, 'ي').replace(/گ/g, 'ك');
// تنظيف نص المستخدم: توحيد + حذف الرموز + اختصار التكرار المبالغ فيه (هلاااا → هلا)
const clean = s => fold(s).replace(/[^\p{L}\p{N}\p{Extended_Pictographic}\s]/gu, ' ').replace(/(.)\1{2,}/gu, '$1').replace(/\s+/g, ' ').trim();

const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const EMO = /\p{Extended_Pictographic}/u;
const PH = [];
function add(alts, replies, mood, max) {
  const parts = fold(alts).split('|').map(x => x.trim()).filter(Boolean).map(x => EMO.test(x) ? esc(x) : '(?<![\\p{L}\\p{N}])' + esc(x) + '(?![\\p{L}\\p{N}])');
  PH.push({ re: new RegExp(parts.join('|'), 'u'), r: replies, m: mood || 'normal', max: max || 99 });
}

